#[derive(Debug, Clone)]
pub struct EditorTheme {
    pub config: ThemeConfig,
    pub opacity: f32,
    pub dimming: f32,
    pub bg_image_path: Option<String>,
}

impl Default for EditorTheme {
    fn default() -> Self {
        Self {
            config: ThemeConfig::for_id(ThemeId::TokyoNight),
            opacity: 0.95,
            dimming: 0.25,
            bg_image_path: None,
        }
    }
}

impl EditorTheme {
    pub fn new(id: ThemeId) -> Self {
        Self {
            config: ThemeConfig::for_id(id),
            opacity: 0.95,
            dimming: 0.25,
            bg_image_path: None,
        }
    }

    pub fn set_theme(&mut self, id: ThemeId) {
        self.config = ThemeConfig::for_id(id);
    }

    pub fn background_with_alpha(&self) -> Color {
        let mut c = self.config.bg;
        c.a = self.opacity;
        c
    }

    pub fn sidebar_with_alpha(&self) -> Color {
        let mut c = self.config.sidebar_bg;
        c.a = self.opacity;
        c
    }
}
